#define PIXELSEND_READY MODULE_P00,3
/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
/* SPI Configuration Registers */
SpiMasterPins_t PixelSend_SpiPins = {
    &IfxQspi1_SCLK_P10_2_OUT,
    &IfxQspi1_MTSR_P10_3_OUT,
    &IfxQspi1_MRSTA_P10_1_IN
};

SpiMaster_t PixelSend_SpiMaster;

SpiMasterCfg_t PixelSend_SpiCfg = {
    &PixelSend_SpiMaster,
    10,
    11,
    12
};

SpiChannel_t PixelSend_SpiChannel;

SpiChannelConfig PixelSend_SpiChannelCfg = {
    &IfxQspi1_SLSO5_P11_2_OUT,
    PIXELSEND_SPIBAUDRATE,
    0,
    SpiIf_ShiftClock_shiftTransmitDataOnLeadingEdge,
    SpiIf_DataHeading_msbFirst
};

uint32 PixelSend_SpiTx[300];
uint32 PixelSend_SpiRx[300];
/*********************************************************************************************************************/
/*--------------------------------------------Private Variables/Constants--------------------------------------------*/
/*********************************************************************************************************************/

