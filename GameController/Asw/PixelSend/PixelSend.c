/*---------------------------------------------Function Implementations----------------------------------------------*/
/*********************************************************************************************************************/
IFX_INTERRUPT(SpimasterTxPixelSend, 0, 10);                  /* SPI Master ISR for transmit data         */
IFX_INTERRUPT(SpimasterRxPixelSend, 0, 11);                  /* SPI Master ISR for receive data          */
IFX_INTERRUPT(SpimasterErPixelSend, 0, 12);                 /* SPI Master ISR for error                 */


 void SpimasterTxPixelSend(void)
 {
     IfxCpu_enableInterrupts();
     IfxQspi_SpiMaster_isrTransmit(PixelSend_SpiCfg.SpiMasterPtr);
 }

 void SpimasterRxPixelSend(void )
 {
     IfxCpu_enableInterrupts();
     IfxQspi_SpiMaster_isrReceive(PixelSend_SpiCfg.SpiMasterPtr);
 }

 void SpimasterErPixelSend(void)
 {
     IfxCpu_enableInterrupts();
     IfxQspi_SpiMaster_isrError(PixelSend_SpiCfg.SpiMasterPtr);
 }


void PixelSend_Init(void)
{
  /* Initialize the Spi Pin */
  Spi_Init(&PixelSend_SpiPins, &PixelSend_SpiCfg);

  Spi_ChannelInit(&PixelSend_SpiCfg, &PixelSend_SpiChannel, &PixelSend_SpiChannelCfg);

  Ports_SetPinInputNoPull(&PIXELSEND_READY);

  /* Wait till the port becomes high */
  while (Ports_GetPinState(&PIXELSEND_READY) == FALSE) {}
}



void PixelSend_SendSpi(uint16 size)
{
  PixelSend_SpiTx[0] = 0x23482428;
  PixelSend_SpiTx[1] = 0xac232df9;
  PixelSend_SpiTx[2] = 0xac232df9;
  PixelSend_SpiTx[3] = 0xac232df9;
  PixelSend_SpiTx[4] = 0xac232df9;
  PixelSend_SpiTx[5] = 0xac232df9;
  PixelSend_SpiTx[6] = 0xac232df9;
  PixelSend_SpiTx[7] = 0xac232df9;

  if (Ports_GetPinState(&PIXELSEND_READY) == FALSE)
  {
    Spi_WriteBytes(&PixelSend_SpiChannel,PixelSend_SpiTx, size);
  }
  else
  {
    /* Here we do nothing */
  }
}
